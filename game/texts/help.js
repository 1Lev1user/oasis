import { BALANCE } from '../../lib/balance.js';

const num = (n) => String(n).replace('.', ',');
const pct = (n) => `${num(n)}%`;
// Russian plural by the number: one (1, 21 ...), few (2-4, 22-24 ...), many (the rest)
const days = (n) => {
  const d = n % 10;
  const h = n % 100;
  return `${n} ${d === 1 && h !== 11 ? 'день' : d >= 2 && d <= 4 && (h < 12 || h > 14) ? 'дня' : 'дней'}`;
};

