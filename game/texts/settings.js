// Russian plural by the number: one (1, 21 ...), few (2-4, 22-24 ...), many (the rest)
const plural = (n, one, few, many) => {
  const d = n % 10;
  const h = n % 100;
  if (d === 1 && h !== 11) return one;
  return d >= 2 && d <= 4 && (h < 12 || h > 14) ? few : many;
};

