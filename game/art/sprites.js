// Pond: an ellipse with a glint, drawn from a formula instead of typed out.
function ellipsePond(pw, ph) {
  const rows = [];
  const inside = (x, y) => x >= 0 && y >= 0 && x < pw && y < ph && ((x + 0.5 - pw / 2) / (pw / 2)) ** 2 + ((y + 0.5 - ph / 2) / (ph / 2)) ** 2 <= 1;
  for (let y = 0; y < ph; y++) {
    let row = '';
    for (let x = 0; x < pw; x++) {
      const dx = (x + 0.5 - pw / 2) / (pw / 2);
      const dy = (y + 0.5 - ph / 2) / (ph / 2);
      const d = dx * dx + dy * dy;
      const glint = (y === 2 && x > 6 && x < 11) || (y === 3 && x > 16 && x < 19);
      row += d > 1 ? '.' : d > 0.72 || [[x - 1, y], [x + 1, y], [x, y - 1], [x, y + 1]].some(([nx, ny]) => !inside(nx, ny)) ? 'K' : glint ? 'J' : y > ph * 0.6 ? 'b' : 'B';
    }
    rows.push(row);
  }
  return rows;
}

